"""Generates the Lean statements of the trial rules from the rule file. Proofs stay hand-written.

Usage: gen_lean.py <rules> <output>          writes the statements
       gen_lean.py <rules> <output> --check  fails if the output is stale

Each semantic guard also gets a statement with that guard dropped, which Lean must refute by witness.
"""

import sys
from pathlib import Path

from lang import metas, pattern_tree, read_forms

TRIAL = ("distribute", "mul-zero", "div-by-fraction", "add-both", "cross-multiply")
HEADER = """-- Generated by oracle/gen_lean.py from rules/rules.sexp. Do not edit.
import SymAlgebra.Semantics

namespace SymAlgebra
"""


def load_trial(path):
    rules = {}
    for form in read_forms(Path(path).read_text(encoding="utf-8")):
        fields = dict(zip(form[2::2], form[3::2]))
        fields["id"] = form[1]
        rules[form[1]] = fields
    missing = [name for name in TRIAL if name not in rules]
    if missing:
        raise ValueError(f"trial rule missing from {path}: {missing}")
    return [rules[name] for name in TRIAL]


def name_of(meta):
    return meta.lstrip("?")


def term(tree, literals):
    if tree[0] == "meta":
        if tree[1] in literals:
            return f"(.lit {name_of(tree[1])})"
        return name_of(tree[1])
    if tree[0] == "num":
        return f"(.lit {tree[1]})"
    if tree[0] in ("add", "mul", "div"):
        return f"(.{tree[0]} {term(tree[1], literals)} {term(tree[2], literals)})"
    raise ValueError(f"no Lean form yet for {tree[0]}")


def hypothesis(guard):
    name, target = guard
    if name == "total":
        return f"Total {name_of(target)}"
    if name == "nonzero-literal":
        return f"{name_of(target)} ≠ 0"
    return None


def statement(rule, dropped=None):
    pattern = pattern_tree(rule[":pattern"])
    replacement = pattern_tree(rule[":replacement"])
    guards = rule[":guards"]
    literals = {g[1] for g in guards if g[0] in ("literal", "nonzero-literal")}
    names = sorted(metas(pattern) | metas(replacement))
    terms = [n for n in names if n not in literals]
    binders = []
    if terms:
        binders.append(f"({' '.join(name_of(n) for n in terms)} : E)")
    if literals:
        binders.append(f"({' '.join(name_of(n) for n in names if n in literals)} : ℚ)")
    if rule[":level"] == "expr":
        if rule[":class"] != "equivalence":
            raise ValueError(f"no Lean form yet for an expr implication: {rule['id']}")
        binders.append("(x : ℝ)")
        body = f"ev {term(pattern, literals)} x = ev {term(replacement, literals)} x"
    else:
        before = " ".join(term(side, literals) for side in pattern[1:])
        after = " ".join(term(side, literals) for side in replacement[1:])
        relation = "=" if rule[":class"] == "equivalence" else "⊆"
        body = f"Sol {before} {relation} Sol {after}"
    hypotheses = [hypothesis(g) for g in guards if g is not dropped and hypothesis(g)]
    return "∀ " + " ".join(binders) + ", " + "".join(h + " → " for h in hypotheses) + body


def lean_name(rule):
    return "rule_" + rule["id"].replace("-", "_")


def render(rules):
    parts = [HEADER]
    for rule in rules:
        parts.append(f"def {lean_name(rule)} : Prop :=\n  {statement(rule)}\n")
        for guard in rule[":guards"]:
            if hypothesis(guard):
                suffix = guard[0].replace("-", "_")
                parts.append(f"def {lean_name(rule)}_needs_{suffix} : Prop :=\n"
                             f"  ¬ ({statement(rule, dropped=guard)})\n")
    parts.append("end SymAlgebra\n")
    return "\n".join(parts)


def main():
    rules_path, output = sys.argv[1:3]
    text = render(load_trial(rules_path))
    target = Path(output)
    if len(sys.argv) > 3:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"LEAN STATEMENTS STALE: {output} differs from {rules_path}")
            sys.exit(1)
        print("COUNT lean-statements ran=1 passed=1")
    else:
        target.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
