"""Generates the Lean statements of the proved rules from the rule file. Proofs stay hand-written.

Usage: gen_lean.py <rules> <output>          writes the statements
       gen_lean.py <rules> <output> --check  fails if the output is stale

Each semantic guard of a trial rule also gets a statement with that guard dropped, which Lean must
refute by witness. Alternatives on the right of a rule are the union of their sets.
"""

import sys
from pathlib import Path

from lang import metas, pattern_tree, read_forms

TRIAL = ("distribute", "mul-zero", "div-by-fraction", "add-both", "cross-multiply")
QUADRATICS = ("expand-product", "square-as-product", "product-as-square", "square-sum", "square-literal",
              "factor-common", "factor-trinomial", "factor-squares", "zero-product", "square-root",
              "take-root", "simplify-root", "root-of-square", "divide-terms", "complete-square",
              "factor-perfect-square", "quadratic-formula", "quadratic-substitute", "factor-leading",
              "factor-number", "factor-number-three")
PROVED = TRIAL + QUADRATICS
HEADER = """-- Generated by oracle/gen_lean.py from rules/rules.sexp. Do not edit.
import SymAlgebra.Semantics

namespace SymAlgebra
"""


def load_rules(path):
    rules = {}
    for form in read_forms(Path(path).read_text(encoding="utf-8")):
        fields = dict(zip(form[2::2], form[3::2]))
        fields["id"] = form[1]
        rules[form[1]] = fields
    missing = [name for name in PROVED if name not in rules]
    if missing:
        raise ValueError(f"proved rule missing from {path}: {missing}")
    return [rules[name] for name in PROVED]


def name_of(meta):
    return meta.lstrip("?")


def arithmetic(tree):
    """An `eval` body as a rational expression."""
    if tree[0] == "meta":
        return name_of(tree[1])
    if tree[0] == "num":
        return str(tree[1])
    if tree[0] == "neg":
        return f"(-{arithmetic(tree[1])})"
    symbol = {"add": "+", "sub": "-", "mul": "*", "div": "/"}[tree[0]]
    return f"({arithmetic(tree[1])} {symbol} {arithmetic(tree[2])})"


def term(tree, literals):
    if tree[0] == "meta":
        if tree[1] in literals:
            return f"(.lit {name_of(tree[1])})"
        return name_of(tree[1])
    if tree[0] == "num":
        return f"(.lit {tree[1]})"
    if tree[0] == "eval":
        return f"(.lit {arithmetic(tree[1])})"
    if tree[0] in ("add", "sub", "mul", "div"):
        return f"(.{tree[0]} {term(tree[1], literals)} {term(tree[2], literals)})"
    if tree[0] in ("neg", "sqrt"):
        return f"(.{tree[0]} {term(tree[1], literals)})"
    if tree[0] == "pow":
        return f"(.pow {term(tree[1], literals)} {tree[2]})"
    raise ValueError(f"no Lean form yet for {tree[0]}")


def hypotheses_of(guard):
    """What a guard says, as Lean hypotheses. The Lisp guards ask for more, such as whole numbers,
    so what is proved here is the stronger statement."""
    name, *targets = guard
    n = [name_of(target) for target in targets]
    if name == "total":
        return [f"Total {n[0]}"]
    if name == "nonzero-literal":
        return [f"{n[0]} ≠ 0"]
    if name == "positive-literal":
        return [f"0 < {n[0]}"]
    if name == "real-discriminant":
        return [f"0 ≤ {n[1]} * {n[1]} - 4 * {n[0]} * {n[2]}"]
    if name == "factors":
        return [f"{n[0]} + {n[1]} = {n[2]}", f"{n[0]} * {n[1]} = {n[3]}"]
    if name == "square-of":
        return [f"{n[0]} * {n[0]} = {n[1]}"]
    if name == "half-square":
        return [f"({n[0]} / 2) * ({n[0]} / 2) = {n[1]}"]
    if name == "split-root":
        return [f"0 < {n[0]}", f"1 < {n[1]}", f"{n[0]} * {n[0]} * {n[1]} = {n[2]}"]
    if name == "splits":
        p, q, a, b, c = n
        return [f"0 < {p}", f"{q} ≠ 0", f"{p} * ({c} / {q}) + {q} * ({a} / {p}) = {b}"]
    if name == "common-factor":
        return [f"1 < {n[0]}"]
    return []


def solution_sets(line, literals):
    if line[0] == "or":
        return " ∪ ".join(solution_sets(item, literals) for item in line[1:])
    return "Sol " + " ".join(term(side, literals) for side in line[1:])


def statement(rule, dropped=None):
    pattern = pattern_tree(rule[":pattern"])
    replacement = pattern_tree(rule[":replacement"])
    guards = rule[":guards"]
    literals = {g[1] for g in guards if g[0] in ("literal", "nonzero-literal", "positive-literal")}
    names = sorted(metas(pattern) | metas(replacement))
    terms = [n for n in names if n not in literals]
    binders = []
    if terms:
        binders.append(f"({' '.join(name_of(n) for n in terms)} : E)")
    if literals:
        binders.append(f"({' '.join(name_of(n) for n in names if n in literals)} : ℚ)")
    if rule[":level"] == "expr":
        if rule[":class"] != "equivalence":
            raise ValueError(f"no Lean form yet for an expr implication: {rule['id']}")
        binders.append("(x : ℝ)")
        body = f"ev {term(pattern, literals)} x = ev {term(replacement, literals)} x"
    else:
        before = " ".join(term(side, literals) for side in pattern[1:])
        relation = "=" if rule[":class"] == "equivalence" else "⊆"
        body = f"Sol {before} {relation} {solution_sets(replacement, literals)}"
    hypotheses = [h for g in guards if g is not dropped for h in hypotheses_of(g)]
    return "∀ " + " ".join(binders) + ", " + "".join(h + " → " for h in hypotheses) + body


def lean_name(rule):
    return "rule_" + rule["id"].replace("-", "_")


def render(rules):
    parts = [HEADER]
    for rule in rules:
        parts.append(f"def {lean_name(rule)} : Prop :=\n  {statement(rule)}\n")
        for guard in rule[":guards"] if rule["id"] in TRIAL else []:
            if hypotheses_of(guard):
                suffix = guard[0].replace("-", "_")
                parts.append(f"def {lean_name(rule)}_needs_{suffix} : Prop :=\n"
                             f"  ¬ ({statement(rule, dropped=guard)})\n")
    parts.append("end SymAlgebra\n")
    return "\n".join(parts)


def main():
    rules_path, output = sys.argv[1:3]
    text = render(load_rules(rules_path))
    target = Path(output)
    if len(sys.argv) > 3:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"LEAN STATEMENTS STALE: {output} differs from {rules_path}")
            sys.exit(1)
        print("COUNT lean-statements ran=1 passed=1")
    else:
        target.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
